/**
 * The generated catalog modules (SPEC 9.1, ADR 0004, 0011): JSON under
 * `as const`, so the module is both data and a precise type, exported
 * through a named interface so that compile errors print the name instead
 * of the catalog, and a parser that reads a committed module back for drift
 * detection.
 * @ref https://www.typescriptlang.org/docs/handbook/2/objects.html#extending-types
 * @packageDocumentation
 */
import type { Catalog, PublicCatalog } from '@nizam-os/catalog-core';

import { CATALOG_FORMAT } from '@nizam-os/catalog-core';

import { PgCatalogError } from '../errors';

/** The first line of every generated file (SPEC 15). */
export const FILE_HEADER =
  '// Generated by @nizam-os/pg-catalog. Do not edit: change the migrations and run `pg-catalog extract`.';
/** The interface `catalog.ts` exports when the configuration names none (SPEC 15). */
export const DEFAULT_CATALOG_INTERFACE = 'ExtractedCatalog';
/** The interface `public-catalog.ts` exports when the configuration names none (SPEC 15). */
export const DEFAULT_PUBLIC_INTERFACE = 'ExtractedPublicCatalog';
/**
 * What a generated interface may be called: an ASCII identifier that starts
 * with an uppercase letter, which no keyword or predefined type name does,
 * since all of them are lowercase.
 */
export const INTERFACE_NAME: RegExp = /^[A-Z][A-Za-z0-9_]*$/u;
const INDENT = 2;
const ASSIGNMENT = '= ';
/** Ends the literal; the lines after it never carry these characters, so the last one is the literal's. */
const TERMINATOR = ' as const;';

/** How a catalog module names its type. */
export interface CatalogModuleOptions {
  /** The exported interface; default `ExtractedCatalog`, or `ExtractedPublicCatalog` for the public module. */
  readonly interface?: string | undefined;
}

function interfaceName(
  caller: string,
  options: CatalogModuleOptions,
  fallback: string,
): string {
  const name = options.interface ?? fallback;
  if (!INTERFACE_NAME.test(name)) {
    throw new TypeError(
      `${caller}: options.interface must be an ASCII identifier that starts with an uppercase letter, not ${JSON.stringify(name)}`,
    );
  }
  return name;
}

/**
 * The literal under a private name, an interface that extends its type, and
 * the binding typed by that interface. TypeScript prints an interface by
 * its name, while an anonymous literal type prints member by member, which
 * dominates the time a compile error takes.
 */
function renderModule(
  binding: string,
  name: string,
  value: Catalog | PublicCatalog,
): string {
  return [
    FILE_HEADER,
    `const value = ${JSON.stringify(value, null, INDENT)}${TERMINATOR}`,
    '',
    `/** The type of \`${binding}\`, by a name compile errors print in place of its members. */`,
    `export interface ${name} extends Readonly<typeof value> {}`,
    '',
    `export const ${binding}: ${name} = value;`,
    '',
  ].join('\n');
}

/**
 * The text of `catalog.ts`: the header line, the literal, and
 * `export const catalog: ExtractedCatalog`, under `options.interface` when
 * given. Throws `TypeError` for an interface name outside `INTERFACE_NAME`.
 */
export function renderCatalogModule(
  catalog: Catalog,
  options: CatalogModuleOptions = {},
): string {
  return renderModule(
    'catalog',
    interfaceName('renderCatalogModule', options, DEFAULT_CATALOG_INTERFACE),
    catalog,
  );
}

/** The text of `public-catalog.ts`, binding `publicCatalog` with the type `ExtractedPublicCatalog` unless `options.interface` names another. */
export function renderPublicCatalogModule(
  publicCatalog: PublicCatalog,
  options: CatalogModuleOptions = {},
): string {
  return renderModule(
    'publicCatalog',
    interfaceName(
      'renderPublicCatalogModule',
      options,
      DEFAULT_PUBLIC_INTERFACE,
    ),
    publicCatalog,
  );
}

function isRecord(value: unknown): value is Readonly<Record<string, unknown>> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/**
 * Whether a parsed module of the current format has the catalog's members.
 * Only the top level is checked: deeper members are JSON the diff compares
 * as values, so a hand edit there shows up as drift instead of a crash.
 */
function declaresCatalog(value: unknown): value is Catalog {
  return (
    isRecord(value) &&
    Array.isArray(value['schemas']) &&
    Array.isArray(value['extensions']) &&
    isRecord(value['enums']) &&
    isRecord(value['domains']) &&
    isRecord(value['tables'])
  );
}

/**
 * Reads a catalog module's text back into the `Catalog` it declares: the
 * JSON between the first `= ` and the last ` as const;`, which also reads
 * a module written before the literal had a private name. Fails with
 * `catalog_unreadable` when the text is not such a module and with
 * `catalog_format` when it was written in another `format`.
 */
export function parseCatalogModule(text: string): Catalog {
  const start = text.indexOf(ASSIGNMENT);
  const end = text.lastIndexOf(TERMINATOR);
  if (start < 0 || end <= start) {
    throw new PgCatalogError(
      'catalog_unreadable',
      'the file is not a catalog module written by pg-catalog extract',
    );
  }
  let value: unknown;
  try {
    value = JSON.parse(text.slice(start + ASSIGNMENT.length, end));
  } catch (error) {
    throw new PgCatalogError(
      'catalog_unreadable',
      'the catalog module does not hold valid JSON',
      { cause: error },
    );
  }
  if (!isRecord(value) || !Object.hasOwn(value, 'format')) {
    throw new PgCatalogError(
      'catalog_unreadable',
      'the catalog module does not declare a catalog',
    );
  }
  if (value['format'] !== CATALOG_FORMAT) {
    throw new PgCatalogError(
      'catalog_format',
      `the catalog module was written in format ${JSON.stringify(value['format'])}; this version reads format ${CATALOG_FORMAT}, so run pg-catalog extract again`,
    );
  }
  if (!declaresCatalog(value)) {
    throw new PgCatalogError(
      'catalog_unreadable',
      'the catalog module does not declare a catalog',
    );
  }
  return value;
}

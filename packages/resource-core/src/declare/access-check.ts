/**
 * The access rules fields and relationships share (SPEC 3.1, 3.3): what
 * the column allows and what the declared operations can write. The
 * runtime twins are `checkColumnAccess` and `checkOperationAccess` in
 * `check-columns.ts`.
 * @packageDocumentation
 */
import type { PublicColumn } from '@nizam-os/catalog-core';

import type { Requirement } from './requirement';
import type { Declaration } from './types';

/** The operations a declaration lists. */
export type OperationOf<TDecl extends Declaration> =
  TDecl['operations'][number];

/** Why a column refuses an access mode (SPEC 3.1), or `never`. */
type ColumnAccessError<
  TColumn extends PublicColumn,
  TAccess,
> = TAccess extends 'read'
  ? never
  : TColumn['generated'] extends null
    ? TColumn['identity'] extends 'always'
      ? 'an identity column generated always is read-only'
      : TColumn['identity'] extends 'byDefault'
        ? TAccess extends 'immutable'
          ? never
          : 'an identity column generated by default is read or immutable'
        : never
    : 'a generated column is read-only';

/** Why the operations cannot write an access mode (SPEC 3.3), or `never`. */
type OperationAccessError<TOps, TAccess> = TAccess extends 'immutable'
  ? 'create' extends TOps
    ? never
    : 'immutable needs the create operation'
  : TAccess extends 'readWrite' | 'write'
    ? [Extract<TOps, 'create' | 'update'>] extends [never]
      ? `${TAccess} needs the create or update operation`
      : never
    : never;

/**
 * A member's access, checked against its column and the operations.
 * Reading is always allowed, so a `read` member returns before the error
 * unions are built.
 */
export type AccessRequirement<
  TColumn extends PublicColumn,
  TOps,
  TAccess,
> = TAccess extends 'read'
  ? unknown
  : [
        | ColumnAccessError<TColumn, TAccess>
        | OperationAccessError<TOps, TAccess>,
      ] extends [never]
    ? unknown
    : Requirement<`access: ${ColumnAccessError<TColumn, TAccess> | OperationAccessError<TOps, TAccess>}`>;

import type { Catalog, PublicCatalog } from '@nizam-os/catalog-core';

import { beforeAll, describe, expect, it } from 'vitest';

import { readReplayed } from '../test-support/replayed';
import { portableMigrations } from '../test-support/schema';
import {
  DEFAULT_CATALOG_INTERFACE,
  DEFAULT_PUBLIC_INTERFACE,
  FILE_HEADER,
  parseCatalogModule,
  renderCatalogModule,
  renderPublicCatalogModule,
} from './catalog-module';

const tiny: Catalog = {
  format: 3,
  schemas: ['public'],
  extensions: [],
  enums: { mood: ['happy', 'sad'] },
  domains: {},
  tables: {},
};
const tinyPublic: PublicCatalog = {
  format: 3,
  enums: {},
  domains: {},
  tables: {},
};

describe('renderCatalogModule (SPEC 9.1)', () => {
  it('writes the header, the literal as JSON with two-space indentation under as const, the interface, and the binding, ending in one newline', () => {
    expect(renderCatalogModule(tiny)).toBe(
      `${FILE_HEADER}
const value = {
  "format": 3,
  "schemas": [
    "public"
  ],
  "extensions": [],
  "enums": {
    "mood": [
      "happy",
      "sad"
    ]
  },
  "domains": {},
  "tables": {}
} as const;

/** The type of \`catalog\`, by a name compile errors print in place of its members. */
export interface ExtractedCatalog extends Readonly<typeof value> {}

export const catalog: ExtractedCatalog = value;
`,
    );
  });

  it('binds the public slice as publicCatalog, typed ExtractedPublicCatalog', () => {
    const text = renderPublicCatalogModule(tinyPublic);
    expect(text.split('\n').slice(0, 2)).toEqual([
      FILE_HEADER,
      'const value = {',
    ]);
    expect(text.split('\n').slice(-5)).toEqual([
      '/** The type of `publicCatalog`, by a name compile errors print in place of its members. */',
      'export interface ExtractedPublicCatalog extends Readonly<typeof value> {}',
      '',
      'export const publicCatalog: ExtractedPublicCatalog = value;',
      '',
    ]);
  });

  it('names the interface options.interface, leaving the literal as it was', () => {
    const named = renderCatalogModule(tiny, { interface: 'SternCatalog' });
    expect(named).toContain(
      'export interface SternCatalog extends Readonly<typeof value> {}',
    );
    expect(named).toContain('export const catalog: SternCatalog = value;');
    expect(named.replaceAll('SternCatalog', 'ExtractedCatalog')).toBe(
      renderCatalogModule(tiny),
    );
    expect(
      renderPublicCatalogModule(tinyPublic, { interface: 'Stern_Public2' }),
    ).toContain('export const publicCatalog: Stern_Public2 = value;');
    expect(renderCatalogModule(tiny, { interface: undefined })).toBe(
      renderCatalogModule(tiny),
    );
  });

  it.each([
    ['empty', ''],
    ['lowercase', 'sternCatalog'],
    ['a predefined type name', 'string'],
    ['a digit first', '2Catalog'],
    ['a dollar sign', 'Stern$Catalog'],
    ['a hyphen', 'Stern-Catalog'],
    ['a non-ASCII letter', 'Ärzte'],
    ['code', 'X {} export const y = 1; interface Z'],
  ])('throws TypeError for an interface name that is %s', (_title, name) => {
    expect(() => renderCatalogModule(tiny, { interface: name })).toThrow(
      new TypeError(
        `renderCatalogModule: options.interface must be an ASCII identifier that starts with an uppercase letter, not ${JSON.stringify(name)}`,
      ),
    );
    expect(() =>
      renderPublicCatalogModule(tinyPublic, { interface: name }),
    ).toThrow(/^renderPublicCatalogModule: options\.interface must be/u);
  });

  it('pins the header text and default interfaces of SPEC 15', () => {
    expect(FILE_HEADER).toBe(
      '// Generated by @nizam-os/pg-catalog. Do not edit: change the migrations and run `pg-catalog extract`.',
    );
    expect([DEFAULT_CATALOG_INTERFACE, DEFAULT_PUBLIC_INTERFACE]).toEqual([
      'ExtractedCatalog',
      'ExtractedPublicCatalog',
    ]);
  });
});

describe('parseCatalogModule (SPEC 9.1)', () => {
  let catalog: Catalog;

  beforeAll(async () => {
    catalog = await readReplayed(portableMigrations, ['public', 'audit']);
  });

  it('reads back exactly the catalog a rendered module declares, for a real schema', () => {
    expect(parseCatalogModule(renderCatalogModule(catalog))).toEqual(catalog);
  });

  it('accepts trailing whitespace an editor may add', () => {
    expect(parseCatalogModule(`${renderCatalogModule(tiny)}\n\n`)).toEqual(
      tiny,
    );
  });

  it('reads a module written before the literal had a private name', () => {
    const earlier = `${FILE_HEADER}\nexport const catalog = ${JSON.stringify(tiny, null, 2)} as const;\n`;
    expect(parseCatalogModule(earlier)).toEqual(tiny);
  });

  it('reads a literal whose strings hold an assignment and the terminator', () => {
    const tricky: Catalog = {
      ...tiny,
      enums: { mood: ['a = b', 'x as const;', '} as const;'] },
    };
    for (const name of ['ExtractedCatalog', 'Tricky']) {
      expect(
        parseCatalogModule(renderCatalogModule(tricky, { interface: name })),
      ).toEqual(tricky);
    }
  });

  it.each([
    ['an empty file', ''],
    [
      'a module without the terminator',
      'export const catalog = {"format": 3};',
    ],
    ['a module without an assignment', '{"format": 3} as const;'],
  ])('fails with catalog_unreadable for %s', (_title, text) => {
    expect(() => parseCatalogModule(text)).toThrow(
      expect.objectContaining({
        code: 'catalog_unreadable',
        message:
          'the file is not a catalog module written by pg-catalog extract',
      }),
    );
  });

  it('fails with catalog_unreadable for invalid JSON, keeping the parse error as the cause', () => {
    let caught: unknown;
    try {
      parseCatalogModule('export const catalog = {format: 3} as const;');
    } catch (error) {
      caught = error;
    }
    expect(caught).toMatchObject({
      code: 'catalog_unreadable',
      message: 'the catalog module does not hold valid JSON',
    });
    expect((caught as Error).cause).toBeInstanceOf(SyntaxError);
  });

  it.each([
    ['an array', 'export const catalog = [] as const;'],
    [
      'an object without a format',
      'export const catalog = {"tables": {}} as const;',
    ],
  ])('fails with catalog_unreadable for %s', (_title, text) => {
    expect(() => parseCatalogModule(text)).toThrow(
      expect.objectContaining({
        code: 'catalog_unreadable',
        message: 'the catalog module does not declare a catalog',
      }),
    );
  });

  it('fails with catalog_format for another format, telling the reader to extract again', () => {
    expect(() =>
      parseCatalogModule('export const catalog = {"format": 4} as const;'),
    ).toThrow(
      expect.objectContaining({
        code: 'catalog_format',
        message:
          'the catalog module was written in format 4; this version reads format 3, so run pg-catalog extract again',
      }),
    );
  });
});

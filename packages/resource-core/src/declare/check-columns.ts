/**
 * Fields and relationships against the catalog (SPEC 3.1, 3.6): what a
 * column may be declared as, which access modes it and the operations
 * allow, codecs and wire forms, and the domain CHECKs a written field needs
 * validators for.
 * @packageDocumentation
 */
import type { PublicColumn, PublicTable } from '@nizam-os/catalog-core';

import type { DefinerContext } from './check-config';
import type {
  Access,
  Declaration,
  FieldDeclaration,
  Operation,
  RelationshipDeclaration,
} from './types';

import {
  codecTypeName,
  foreignKeyOf,
  hasWireForm,
  isIdentifierColumn,
  isSearchColumn,
  primaryKeyColumn,
  resolveColumnType,
} from '../catalog/columns';
import { idSpelling } from '../catalog/id-spelling';
import { ownValue } from '../internal/object';

/** What every member check needs: the definer, the table, and the declaration's facts. */
export interface MemberScope {
  readonly context: DefinerContext;
  readonly table: string;
  readonly tableDef: PublicTable;
  readonly operations: ReadonlySet<Operation>;
  readonly scopeColumn: string | undefined;
}

function columnOf(
  scope: MemberScope,
  path: string,
  column: string,
): PublicColumn {
  const columnDef = ownValue(scope.tableDef.columns, column);
  if (columnDef === undefined) {
    throw new TypeError(
      `${path}: "${column}" is not a column of ${scope.table}`,
    );
  }
  if (column === primaryKeyColumn(scope.tableDef)) {
    throw new TypeError(`${path}: the primary key is the resource id`);
  }
  return columnDef;
}

/** The access modes a column allows (SPEC 3.1), or `null` for all. */
function checkColumnAccess(
  path: string,
  column: PublicColumn,
  access: Access,
): void {
  if (column.generated !== null && access !== 'read') {
    throw new TypeError(`${path}.access: a generated column is read-only`);
  }
  if (column.identity === 'always' && access !== 'read') {
    throw new TypeError(
      `${path}.access: an identity column generated always is read-only`,
    );
  }
  if (
    column.identity === 'byDefault' &&
    access !== 'read' &&
    access !== 'immutable'
  ) {
    throw new TypeError(
      `${path}.access: an identity column generated by default is read or immutable`,
    );
  }
}

/** The operations an access mode needs (SPEC 3.3). */
function checkOperationAccess(
  path: string,
  operations: ReadonlySet<Operation>,
  access: Access,
): void {
  if (access === 'immutable' && !operations.has('create')) {
    throw new TypeError(`${path}.access: immutable needs the create operation`);
  }
  if (
    (access === 'readWrite' || access === 'write') &&
    !operations.has('create') &&
    !operations.has('update')
  ) {
    throw new TypeError(
      `${path}.access: ${access} needs the create or update operation`,
    );
  }
}

/** Domain CHECKs without a rule must be covered by the definer when the field is written (SPEC 3.6). */
function checkDomainCoverage(
  scope: MemberScope,
  path: string,
  domains: ReadonlyArray<string>,
): void {
  for (const domainName of domains) {
    const domain = ownValue(scope.context.catalog.domains, domainName);
    for (const [name, constraint] of Object.entries(
      domain?.constraints ?? {},
    )) {
      const covered = ownValue(
        ownValue(scope.context.domains, domainName) ?? {},
        name,
      );
      if (constraint.rule === null && covered === undefined) {
        throw new TypeError(
          `${path}: domain ${domainName}'s CHECK ${name} has no rule; give it a validator in createDeclareResource domains`,
        );
      }
    }
  }
}

function checkCodec(
  scope: MemberScope,
  path: string,
  column: PublicColumn,
  codec: string,
): void {
  const definition = ownValue(scope.context.codecs, codec);
  if (definition === undefined) {
    throw new TypeError(
      `${path}.codec: "${codec}" is not a codec of createDeclareResource`,
    );
  }
  const typeName = codecTypeName(column);
  if (!definition.types.includes(typeName)) {
    throw new TypeError(
      `${path}.codec: codec "${codec}" does not accept type ${typeName}`,
    );
  }
}

function checkField(
  scope: MemberScope,
  column: string,
  field: FieldDeclaration,
): void {
  const path = `${scope.table}.fields.${column}`;
  const columnDef = columnOf(scope, path, column);
  if (foreignKeyOf(scope.tableDef, column) !== undefined) {
    throw new TypeError(
      `${path}: a foreign-key column is declared under relationships`,
    );
  }
  if (column === scope.scopeColumn) {
    throw new TypeError(
      `${path}: the scope column is written by the server, never declared as a field`,
    );
  }
  if (isSearchColumn(columnDef)) {
    throw new TypeError(
      `${path}: a tsvector column is declared as search.column`,
    );
  }
  checkColumnAccess(path, columnDef, field.access);
  checkOperationAccess(path, scope.operations, field.access);
  const resolved = resolveColumnType(scope.context.catalog, columnDef, path);
  if (field.codec !== undefined) {
    checkCodec(scope, path, columnDef, field.codec);
  } else if (!hasWireForm(resolved)) {
    throw new TypeError(
      `${path}: type ${codecTypeName(columnDef)} has no wire form; name a codec`,
    );
  }
  if (field.access !== 'read') {
    checkDomainCoverage(scope, path, resolved.domains);
  }
}

/**
 * Refuses a column that spells ids unlike the key it references (SPEC
 * 3.1), since a relationship's text is its linkage, which must name the
 * target's resource id as the target spells it (SPEC 3.4).
 */
function checkSpelling(
  scope: MemberScope,
  path: string,
  columnDef: PublicColumn,
  target: string,
  targetDef: PublicTable,
  key: string,
): void {
  const keyDef = ownValue(targetDef.columns, key);
  if (keyDef === undefined) {
    throw new TypeError(`${path}: ${key} is not a column of ${target}`);
  }
  const { catalog } = scope.context;
  if (
    idSpelling(catalog, columnDef, path) !== idSpelling(catalog, keyDef, path)
  ) {
    throw new TypeError(
      `${path}: type ${columnDef.sqlType} spells ids unlike ${keyDef.sqlType}, the type of ${target}.${key}`,
    );
  }
}

function checkRelationship(
  scope: MemberScope,
  column: string,
  relationship: RelationshipDeclaration,
): void {
  const path = `${scope.table}.relationships.${column}`;
  const columnDef = columnOf(scope, path, column);
  const foreignKey = foreignKeyOf(scope.tableDef, column);
  if (foreignKey === undefined) {
    throw new TypeError(
      `${path}: "${column}" is not the column of a single-column foreign key`,
    );
  }
  const { table: target, columns } = foreignKey.references;
  const targetDef = ownValue(scope.context.catalog.tables, target);
  if (targetDef === undefined) {
    throw new TypeError(
      `${path}: the foreign key references ${target}, which is not a table of the public catalog`,
    );
  }
  if (columns[0] !== primaryKeyColumn(targetDef)) {
    throw new TypeError(
      `${path}: the foreign key references ${target}.${String(columns[0])}, which is not its primary key`,
    );
  }
  if (!isIdentifierColumn(scope.context.catalog, columnDef, path)) {
    throw new TypeError(
      `${path}: type ${codecTypeName(columnDef)} cannot carry a resource id`,
    );
  }
  checkSpelling(scope, path, columnDef, target, targetDef, String(columns[0]));
  if (column === scope.scopeColumn && relationship.access !== 'read') {
    throw new TypeError(`${path}.access: the scope column is read-only`);
  }
  checkColumnAccess(path, columnDef, relationship.access);
  checkOperationAccess(path, scope.operations, relationship.access);
}

/** Checks every field and relationship of a declaration. */
export function checkMembers(
  scope: MemberScope,
  declaration: Declaration,
): void {
  for (const [column, field] of Object.entries(declaration.fields)) {
    checkField(scope, column, field);
  }
  for (const [column, relationship] of Object.entries(
    declaration.relationships ?? {},
  )) {
    checkRelationship(scope, column, relationship);
  }
}
